/// Task represents a request to the agent
#[derive(Debug, Clone)]
pub struct Task {
    /// Unique task identifier
    pub id: String,
    /// Task description
    pub description: String,
    /// Additional context
    pub context: serde_json::Value,
}

impl Task {
    /// Whether THIS execution runs unattended (no human to answer an MCP
    /// validation modal).
    ///
    /// Read from the task context key `is_detached`, stamped by
    /// [`stamp_detached`] on sub-agent tasks built by a detached parent
    /// (spawn / delegate / parallel). Absent → `false`, the safe default for
    /// the standard attended `/agent` path.
    ///
    /// This is the per-execution detached signal that
    /// `LLMAgent::execute_with_mcp` threads into the tool loop so the
    /// MCP allowlist gate applies transitively: a sub-agent of a detached run
    /// is itself detached, even though the registered agent's own context was
    /// created attended. Carried on the task (not the agent) because the same
    /// registered agent can be invoked attended (`/agent`) or detached (as a
    /// delegate of a detached worker re-run).
    pub fn is_detached(&self) -> bool {
        self.context
            .get("is_detached")
            .and_then(|v| v.as_bool())
            .unwrap_or(false)
    }

    /// Whether this execution is a DELEGATED sub-agent run (DelegateTask or
    /// ParallelTasks), as opposed to a direct run or a SPAWNED sub-agent.
    ///
    /// Read from the task context keys `is_delegation` / `is_parallel_task`
    /// (set by the respective tools). Deliberately EXCLUDES `is_sub_agent`
    /// (Spawn): a spawned sub-agent clones the parent's allowlist (same
    /// privilege, no confused-deputy), so it is gated like a direct detached
    /// run, not subject to the per-entry `allow_in_delegated_runs` flag.
    ///
    /// Combined with [`Task::is_detached`] at the MCP allowlist gate: a tool
    /// armed for an agent is auto-approved in a delegated detached run ONLY if
    /// its allowlist entry also sets `allow_in_delegated_runs` — closing the
    /// UNION confused-deputy where a detached worker delegates to a standard
    /// agent whose own allowlist arms tools the worker should not trigger.
    pub fn is_delegated(&self) -> bool {
        ["is_delegation", "is_parallel_task"].iter().any(|key| {
            self.context
                .get(*key)
                .and_then(|v| v.as_bool())
                .unwrap_or(false)
        })
    }
}

/// Stamps the parent's detached status onto a sub-agent task context.
///
/// The sub-agent tools (SpawnAgent / DelegateTask / ParallelTasks) call this
/// when building the task they hand to the orchestrator, so a sub-agent of a
/// detached parent is itself detached. Without it the sub-agent's MCP calls
/// would hit the interactive validation modal with no human present →
/// stall-until-timeout (helper present) or fail-OPEN (helper absent), which is
/// exactly the threat the per-agent allowlist gate closes.
///
/// No-op when `context` is not a JSON object (the value then resolves to the
/// safe `false` via [`Task::is_detached`]).
pub(crate) fn stamp_detached(context: &mut serde_json::Value, is_detached: bool) {
    if let Some(obj) = context.as_object_mut() {
        obj.insert(
            "is_detached".to_string(),
            serde_json::Value::Bool(is_detached),
        );
    }
}

/// Report generated by an agent (Markdown format)
#[derive(Debug, Clone)]
pub struct Report {
    /// Report status
    pub status: ReportStatus,
    /// Full markdown report content (for DB/export)
    pub content: String,
    /// Pure LLM response content only (for display in chat bubble)
    pub response: String,
    /// Execution metrics
    pub metrics: ReportMetrics,
}

/// Report status
#[derive(Debug, Clone)]
pub enum ReportStatus {
    Success,
    Failed,
}

/// Source of a reasoning step
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReasoningSource {
    /// Synthetic descriptions from agent flow (e.g. "Analyzing task...", "Calling tool X...")
    AgentFlow,
    /// Real thinking content from reasoning models (e.g. Mistral Magistral)
    ModelThinking,
}

impl std::fmt::Display for ReasoningSource {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ReasoningSource::AgentFlow => write!(f, "agent_flow"),
            ReasoningSource::ModelThinking => write!(f, "model_thinking"),
        }
    }
}

/// Intermediate reasoning step data for persistence
#[derive(Debug, Clone)]
pub struct ReasoningStepData {
    /// Content of the reasoning step
    pub content: String,
    /// Duration in milliseconds (from start of execution to this step)
    pub duration_ms: u64,
    /// Global ordering sequence within the execution
    pub sequence: u32,
    /// Source of this reasoning step
    pub source: ReasoningSource,
}

/// Detailed tool execution data for persistence
#[derive(Debug, Clone)]
pub struct ToolExecutionData {
    /// Tool type ("local" or "mcp")
    pub tool_type: String,
    /// Tool name (e.g., "MemoryTool", "find_symbol")
    pub tool_name: String,
    /// MCP server name (only for MCP tools)
    pub server_name: Option<String>,
    /// Input parameters as JSON
    pub input_params: serde_json::Value,
    /// Output result as JSON
    pub output_result: serde_json::Value,
    /// Whether execution was successful
    pub success: bool,
    /// Error message if failed
    pub error_message: Option<String>,
    /// Duration in milliseconds
    pub duration_ms: u64,
    /// Iteration number in the tool loop
    pub iteration: u32,
    /// Global ordering sequence within the execution
    pub sequence: u32,
}

/// Metrics collected during task execution
#[derive(Debug, Clone)]
pub struct ReportMetrics {
    /// Duration in milliseconds
    pub duration_ms: u64,
    /// Cumulative input tokens billed across all LLM API calls (for cost calculation)
    pub tokens_input: usize,
    /// Output tokens generated (cumulative across all iterations)
    pub tokens_output: usize,
    /// Last API call's input tokens (context window size for display)
    pub context_tokens: usize,
    /// Cached input tokens - cache reads (if provider supports prompt caching)
    pub cached_tokens: Option<usize>,
    /// Cache-write tokens (if provider supports prompt caching)
    pub cache_write_tokens: Option<usize>,
    /// Thinking/reasoning tokens (if reasoning model used)
    pub thinking_tokens: Option<usize>,
    /// Provider-reported cost in USD when available (sum across iterations).
    /// `Some` only for providers that report cost directly (e.g. OpenRouter
    /// `usage.cost`); takes precedence over local pricing calculation.
    pub provider_cost_usd: Option<f64>,
    /// Tools used (names only, for backward compatibility)
    pub tools_used: Vec<String>,
    /// MCP calls made (names only, for backward compatibility)
    pub mcp_calls: Vec<String>,
    /// Detailed tool execution data for persistence
    pub tool_executions: Vec<ToolExecutionData>,
    /// Intermediate reasoning steps collected during execution
    pub reasoning_steps: Vec<ReasoningStepData>,
    /// Per-iteration token breakdown (one entry per LLM API call in tool loop)
    pub iteration_metrics: Vec<IterationMetrics>,
}

impl ReportMetrics {
    /// Creates a ReportMetrics with all fields zeroed/empty.
    ///
    /// Use this for early-return error reports where no LLM call was made.
    /// Accepts `duration_ms` since even failed reports track elapsed time.
    pub fn empty(duration_ms: u64) -> Self {
        Self {
            duration_ms,
            tokens_input: 0,
            tokens_output: 0,
            context_tokens: 0,
            cached_tokens: None,
            cache_write_tokens: None,
            thinking_tokens: None,
            provider_cost_usd: None,
            tools_used: vec![],
            mcp_calls: vec![],
            tool_executions: vec![],
            reasoning_steps: vec![],
            iteration_metrics: vec![],
        }
    }
}

impl Report {
    /// Creates a failed report with a formatted error message.
    ///
    /// Provides consistent formatting for error reports across the agent.
    ///
    /// # Arguments
    /// * `agent_id` - The agent identifier (for the report header)
    /// * `task_description` - Description of the task that failed
    /// * `error_msg` - The error message to include
    /// * `duration_ms` - Elapsed time in milliseconds
    pub fn failed(
        agent_id: &str,
        task_description: &str,
        error_msg: String,
        duration_ms: u64,
    ) -> Self {
        Self {
            status: ReportStatus::Failed,
            content: format!(
                "# Agent Report: {}\n\n**Task**: {}\n\n**Status**: Failed\n\n## Error\n{}",
                agent_id, task_description, error_msg
            ),
            response: error_msg,
            metrics: ReportMetrics::empty(duration_ms),
        }
    }

    /// Creates a failed report with partial metrics (from a tool execution loop).
    ///
    /// Use this when an LLM call fails mid-execution and some token/tool metrics
    /// have already been accumulated.
    ///
    /// # Arguments
    /// * `agent_id` - The agent identifier (for the report header)
    /// * `task_description` - Description of the task that failed
    /// * `error_msg` - The error message to include
    /// * `metrics` - Accumulated metrics from partial execution
    pub fn failed_with_metrics(
        agent_id: &str,
        task_description: &str,
        error_msg: String,
        metrics: ReportMetrics,
    ) -> Self {
        Self {
            status: ReportStatus::Failed,
            content: format!(
                "# Agent Report: {}\n\n**Task**: {}\n\n**Status**: Failed\n\n## Error\n\n{}",
                agent_id, task_description, error_msg
            ),
            response: error_msg,
            metrics,
        }
    }
}

/// Agent trait - unified interface for all agents
#[async_trait]
pub trait Agent: Send + Sync {
    /// Executes a task and returns a report
    ///
    /// This is the legacy method without MCP support.
    /// New implementations should prefer `execute_with_mcp`.
    async fn execute(&self, task: Task) -> anyhow::Result<Report>;

    /// Executes a task with access to MCP tools and optional cancellation support.
    ///
    /// This method allows the agent to call MCP tools during execution.
    /// The default implementation delegates to `execute()` for backward compatibility.
    ///
    /// # Arguments
    /// * `task` - The task to execute
    /// * `mcp_manager` - Optional MCP manager for tool invocation
    /// * `cancellation_token` - Optional cancellation token for graceful shutdown.
    ///   When provided, the agent should propagate this token to sub-agent tools
    ///   so they can abort when the user cancels the workflow.
    ///
    /// # Returns
    /// A report containing the execution results and metrics
    async fn execute_with_mcp(
        &self,
        task: Task,
        _mcp_manager: Option<Arc<MCPManager>>,
        _cancellation_token: Option<CancellationToken>,
    ) -> anyhow::Result<Report> {
        // Default implementation for backward compatibility
        self.execute(task).await
    }

    /// Returns agent capabilities
    fn capabilities(&self) -> Vec<String>;

    /// Returns lifecycle type
    fn lifecycle(&self) -> Lifecycle;

    /// Returns available tools
    fn tools(&self) -> Vec<String>;

    /// Returns required MCP servers
    fn mcp_servers(&self) -> Vec<String>;

    /// Returns agent configuration
    fn config(&self) -> &AgentConfig;
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn task_with(context: serde_json::Value) -> Task {
        Task {
            id: "t".to_string(),
            description: "d".to_string(),
            context,
        }
    }

    #[test]
    fn task_is_not_detached_by_default() {
        // Absent key -> attended (the safe default for the standard /agent path,
        // and for any sub-agent task built by an attended parent).
        assert!(!task_with(json!({})).is_detached());
        assert!(!task_with(json!({"is_sub_agent": true})).is_detached());
        // Explicit false stays false.
        assert!(!task_with(json!({"is_detached": false})).is_detached());
    }

    #[test]
    fn stamp_detached_round_trips_through_task_is_detached() {
        // The write seam (sub-agent task builders: spawn / delegate / parallel)
        // and the read seam (LLMAgent::execute_with_mcp) must agree: a context
        // stamped detached resolves detached, so the MCP allowlist gate
        // applies transitively to a sub-agent of a detached parent.
        let mut ctx = json!({"is_sub_agent": true, "workflow_id": "wf"});
        stamp_detached(&mut ctx, true);
        assert!(task_with(ctx).is_detached());

        let mut ctx2 = json!({"is_delegation": true});
        stamp_detached(&mut ctx2, false);
        assert!(!task_with(ctx2).is_detached());
    }

    #[test]
    fn stamp_detached_is_noop_on_non_object() {
        // Defensive: stamping a non-object context must not panic; the value is
        // left untouched and resolves to the safe `false`.
        let mut v = json!("not an object");
        stamp_detached(&mut v, true);
        assert!(!task_with(v).is_detached());
    }

    #[test]
    fn is_delegated_covers_delegate_and_parallel_but_not_spawn() {
        // Delegate / Parallel sub-agents ARE delegated runs (delegation flag applies).
        assert!(task_with(json!({"is_delegation": true})).is_delegated());
        assert!(task_with(json!({"is_parallel_task": true})).is_delegated());
        // A SPAWNED sub-agent is NOT delegated: it clones the parent's allowlist
        // (same privilege), so it is gated like a direct detached run and the
        // per-entry allow_in_delegated_runs flag must NOT apply to it.
        assert!(!task_with(json!({"is_sub_agent": true})).is_delegated());
        // Primary / direct run.
        assert!(!task_with(json!({})).is_delegated());
    }
}
